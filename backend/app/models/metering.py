"""ERP sessions, consumption intervals, command audit (spec §4.6, §4.7, D10, D13).

There is no price column anywhere here. The cabinet measures; the ERP prices,
and only in billing_records (D0, D4, §12). A test asserts the absence.
"""
from sqlalchemy import (
    BigInteger, Boolean, CheckConstraint, Column, DateTime, ForeignKey, Integer, Numeric,
    String, Text, UniqueConstraint,
)

from ..database import Base
from ..utils.time import utcnow


class ErpSession(Base):
    """The ERP's record of one session. The cabinet's id is a foreign key, not ours.

    `erp_ref` is generated by the ERP BEFORE the cabinet knows anything, sent in
    /api/nfc/scan and returned by the cabinet on its session (R14, accepted
    2026-10-12). So `cabinet_session_id` is NULL until the cabinet reports.
    """
    __tablename__ = "sessions"
    __table_args__ = (
        UniqueConstraint("erp_ref", name="uq_sessions_erp_ref"),
        UniqueConstraint("cabinet_id", "cabinet_session_id", name="uq_sessions_cabinet_session"),
        CheckConstraint("session_type IN ('electricity', 'water')", name="ck_sessions_type"),
        CheckConstraint("status IN ('reserved', 'active', 'ended')", name="ck_sessions_status"),
        CheckConstraint(
            "consumption_source IS NULL OR consumption_source IN "
            "('register', 'integrated_legacy', 'unknown')", name="ck_sessions_source"),
        CheckConstraint(
            "billing_state IN ('pending', 'billed', 'manual_review', 'not_billable')",
            name="ck_sessions_billing_state"),
        # NULL is "not known", never 0 — a billed session must have its figure
        CheckConstraint(
            "billing_state <> 'billed' OR "
            "(session_type = 'electricity' AND energy_kwh IS NOT NULL) OR "
            "(session_type = 'water' AND water_liters IS NOT NULL)",
            name="ck_sessions_billed_has_figure"),
    )

    id = Column(BigInteger().with_variant(Integer, "sqlite"), primary_key=True)
    erp_ref = Column(String(64), nullable=False)
    cabinet_id = Column(Integer, ForeignKey("cabinets.id"), nullable=False)
    cabinet_session_id = Column(Integer, nullable=True)
    outlet_id = Column(Integer, ForeignKey("outlets.id"), nullable=False)
    customer_id = Column(Integer, ForeignKey("customers.id"), nullable=True)
    session_type = Column(String(20), nullable=False)
    status = Column(String(10), nullable=False)
    activated_at = Column(DateTime, nullable=True)
    ended_at = Column(DateTime, nullable=True)
    duration_min = Column(Numeric(10, 2), nullable=True)
    energy_kwh = Column(Numeric(12, 4), nullable=True)
    water_liters = Column(Numeric(12, 3), nullable=True)
    meter_e_start = Column(Numeric(14, 4), nullable=True)
    meter_e_end = Column(Numeric(14, 4), nullable=True)
    meter_w_start = Column(Numeric(14, 3), nullable=True)
    meter_w_end = Column(Numeric(14, 3), nullable=True)
    consumption_source = Column(String(20), nullable=True)
    recompute_ok = Column(Boolean, nullable=True)
    billing_state = Column(String(20), nullable=False, default="pending",
                           server_default="pending")
    created_at = Column(DateTime, nullable=False, default=utcnow)


class ConsumptionInterval(Base):
    """Register differences. Aggregates sum THESE, never session fields (§4.6, D10)."""
    __tablename__ = "consumption_intervals"

    id = Column(BigInteger().with_variant(Integer, "sqlite"), primary_key=True)
    session_id = Column(BigInteger, ForeignKey("sessions.id", ondelete="CASCADE"),
                        nullable=False, index=True)
    from_at = Column(DateTime, nullable=False)
    to_at = Column(DateTime, nullable=False)
    energy_kwh = Column(Numeric(12, 4), nullable=True)
    water_liters = Column(Numeric(12, 3), nullable=True)
    source = Column(String(20), nullable=False)


class CommandAudit(Base):
    """EVERY control command (D13 layer 1, §4.7)."""
    __tablename__ = "command_audit"
    __table_args__ = (
        CheckConstraint("actor_type IN ('customer_nfc', 'operator', 'erp_auto')",
                        name="ck_command_audit_actor"),
        CheckConstraint("tag_source IS NULL OR tag_source IN ('scan', 'mapping')",
                        name="ck_command_audit_tag_source"),
        # an operator's command without a reason is refused by the database (§1.0 / 1.1)
        CheckConstraint(
            "actor_type <> 'operator' OR (reason IS NOT NULL AND length(trim(reason)) > 0)",
            name="ck_command_audit_operator_reason"),
    )

    id = Column(BigInteger().with_variant(Integer, "sqlite"), primary_key=True)
    cabinet_id = Column(Integer, ForeignKey("cabinets.id"), nullable=False)
    outlet_id = Column(Integer, ForeignKey("outlets.id"), nullable=True)
    endpoint_key = Column(String(100), nullable=False)
    action = Column(String(30), nullable=False)
    actor_type = Column(String(20), nullable=False)
    actor_ref = Column(String(320), nullable=True)
    tag_source = Column(String(10), nullable=True)
    reason = Column(Text, nullable=True)
    request_url = Column(Text, nullable=False)        # the full URL — catches a doubled ext
    http_status = Column(Integer, nullable=True)
    detail = Column(Text, nullable=True)              # the cabinet's text, tells 409s apart
    source_ip = Column(String(64), nullable=True)
    created_at = Column(DateTime, nullable=False, default=utcnow, index=True)
